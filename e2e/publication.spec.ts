import { expect, test } from "@playwright/test";
import { openPage } from "./navigation";
test.use({ serviceWorkers: "block" });
test("掲載先を選び、校正依頼から本文とURLの最終確認まで進められる", async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const created=await page.request.post("/api/reports",{data:{title:"掲載許可のテスト",reportDate:"2026-08-20",activityArea:"ロボット",contentCategory:"進捗",activityText:"変更しない元の日報"}});
  expect(created.ok()).toBe(true);
  const report=await created.json();
  expect((await page.request.post(`/api/reports/${report.id}/publish`)).ok()).toBe(true);
  await openPage(page,`/reports/${report.id}`);
  await page.getByRole("button",{name:"投稿への掲載許可を依頼する",exact:true}).click();
  await page.getByLabel("note",{exact:true}).check();
  await page.getByLabel("その他",{exact:true}).check();
  await page.getByLabel("その他の掲載先",{exact:true}).fill("チーム広報誌");
  await page.getByLabel("依頼メッセージ",{exact:true}).fill("活動を紹介したいです");
  await page.getByRole("button",{name:"掲載許可を依頼してDMを送る"}).click();
  await expect(page).toHaveURL(/\/publication-requests\/[0-9a-f-]+$/, { timeout: 20_000 });
  await page.getByRole("button",{name:"校正を依頼した上で公開を許可する",exact:true}).click();
  await page.getByLabel("校正を依頼する内容",{exact:true}).fill("個人名を伏せてください");
  await page.getByRole("button",{name:"この内容で返事を送る"}).click();
  await expect(page.getByRole("status",{name:"掲載許可の状態"})).toHaveText("校正・確認用原稿の準備中");
  await page.getByLabel("確認用の投稿本文",{exact:true}).fill("公開前の校正済み本文");
  await page.getByLabel("確認用URL",{exact:true}).fill("https://note.com/preview/hanabi");
  await page.getByRole("button",{name:"投稿本文とURLをDMで送る"}).click();
  await expect(page.getByRole("status",{name:"掲載許可の状態"})).toHaveText("投稿者の最終確認待ち");
  await page.getByLabel("修正してほしい内容・コメント",{exact:true}).fill("最終確認しました");
  await page.getByRole("button",{name:"この投稿本文・URLで公開を許可する"}).click();
  await expect(page.getByRole("status",{name:"掲載許可の状態"})).toHaveText("掲載許可済み");
  await page.reload();
  await expect(page.getByRole("status",{name:"掲載許可の状態"})).toHaveText("掲載許可済み");
  await expect(page.getByRole("link",{name:"確認用URLを開く ↗"})).toHaveAttribute("href","https://note.com/preview/hanabi");
  expect((await (await page.request.get(`/api/reports/${report.id}`)).json()).activityText).toBe("変更しない元の日報");
  await expect(page.locator(".initial-loading")).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath("publication.png"),fullPage:true});
});
